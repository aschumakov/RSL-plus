import { createHash } from "crypto";

/**
 * Отпечаток содержимого файла: размер в байтах и sha1.
 *
 * Единственное надёжное основание считать файл неизменившимся. Дата изменения
 * им не является: её сохраняют системы контроля версий, архиваторы и утилиты
 * копирования, а файловые системы округляют её до одной-двух секунд. Размер
 * тоже не спасает — правка «Alpha» на «Bravo» его не меняет. Кэш, который
 * доверяет дате и размеру, в таком случае молча отдаёт устаревшие данные, и
 * заметно это не по ошибке, а по пропавшим результатам поиска.
 *
 * Размер входит в ключ не ради надёжности sha1, а чтобы совпадение отпечатков
 * файлов разной длины было невозможным, а не «маловероятным», и чтобы значение
 * читалось в логах.
 */
export function contentFingerprint(content: Buffer | string): string {
    const buffer = typeof content === "string"
        ? Buffer.from(content, "utf8")
        : content;
    return `${buffer.length}:${createHash("sha1")
        .update(buffer)
        .digest("hex")}`;
}

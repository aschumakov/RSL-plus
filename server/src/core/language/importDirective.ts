/**
 * Где слово Import начинает директиву, а где это обычное имя.
 *
 * Правило было своим у каждого из пяти извлекателей, и они разошлись на живом
 * коде. Одни считали директивой любое вхождение слова, другие — только начало
 * предложения. Из-за этого у четырёх файлов проекта фоновый каталог, быстрые
 * подсказки и полный разбор открытого документа имели разный список Import.
 *
 * Правило одно и опирается на предыдущий значимый токен:
 *
 *   его нет вовсе      — начало файла;
 *   `;`                — обычный конец предложения;
 *   `.` и `:`          — предыдущее предложение закрыто небрежно. Так написаны
 *                        четыре настоящие директивы проекта, и отвергать их
 *                        нельзя: файл перестанет видеть свои зависимости;
 *   `end`              — конец блока без точки с запятой.
 *
 * Всё остальное — не директива. После имени, числа, строки, запятой, знака
 * равенства или открывающей скобки слово Import стоит внутри выражения:
 * `Var Import = 1;` объявляет переменную, а не подключает модуль.
 */

/** Слово Import: длина проверяется раньше регистра — она отсекает почти всё. */
export function isRslImportWord(
    token: { kind: string; value: string }
): boolean {
    return token.kind === "identifier" &&
        token.value.length === 6 &&
        token.value.toLowerCase() === "import";
}

/**
 * Начинает ли слово Import директиву в этом месте.
 *
 * Передаётся предыдущий ЗНАЧИМЫЙ токен — пробелы и комментарии между ним и
 * словом Import значения не имеют.
 */
/**
 * Слова, после которых Import — объявляемое имя, а не директива.
 *
 * `Var Import = 1;` объявляет переменную. Список тот же, что у объявлений:
 * после любого из этих слов идёт имя.
 */
const DECLARING_WORDS = new Set([
    "var",
    "const",
    "array",
    "file",
    "record",
    "class",
    "macro",
    "local",
    "private",
    "public",
    "static"
]);

/**
 * Знаки, после которых ожидается операнд, а не новое предложение.
 *
 * Точка и двоеточие сюда не входят намеренно: после них в проекте стоят
 * четыре настоящие директивы.
 */
const OPERAND_SYMBOLS = new Set([
    "=", "==", "!=", "<", ">", "<=", ">=",
    "+", "-", "*", "/", "%",
    "&", "|", "!", "^",
    ",", "(", "["
]);

export function startsRslImportDirective(
    previous: { kind: string; raw: string; value: string } | undefined,
    next?: { kind: string; raw: string } | undefined
): boolean {
    /*
     * За словом Import обязано идти имя модуля.
     *
     * Одного взгляда назад мало: `Import = Import + 1;` стоит в начале
     * предложения и по предыдущему токену неотличимо от директивы. Отличает
     * следующий: у директивы это имя или строка, а не знак операции.
     */
    if (next && next.kind !== "identifier" && next.kind !== "string") {
        return false;
    }

    if (!previous) {
        return true;
    }

    /*
     * Правило от обратного: перечислены места, где Import директивой быть не
     * может. Перечислять места, где может, оказалось нельзя — их слишком много
     * и они разные: после `;`, после `.` и `:`, после `end`, после `)`
     * заголовка Macro. Последнее и сломалось, когда список был разрешительным:
     * проверка «Import внутри Macro» перестала находить свою же ошибку.
     */
    if (previous.kind === "symbol") {
        return !OPERAND_SYMBOLS.has(previous.raw);
    }

    if (previous.kind === "identifier") {
        return !DECLARING_WORDS.has(previous.value.toLowerCase());
    }

    /* После числа или строки предложение не начинается. */
    return false;
}

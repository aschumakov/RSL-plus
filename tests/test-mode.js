"use strict";

/**
 * Быстрый набор или полный.
 *
 * Быстрый — ежедневная проверка: функциональность, регрессии известных
 * дефектов и короткие проверки гонок. Длинные дифференциальные прогоны,
 * фаззинг, проверки конкуренции и роста времени идут в полном наборе: они
 * ценны, но ждать их на каждый прогон незачем.
 *
 * Значение приходит из прогонщика (`RSL_TESTS`). Запуск файла руками — всегда
 * полный: иначе легко решить, что проверка прошла, когда она даже не
 * запускалась.
 */
function isFullTestRun() {
    return process.env.RSL_TESTS !== "fast";
}

module.exports = { isFullTestRun };
